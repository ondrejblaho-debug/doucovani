// Generates dist/sw.js with a precache list of every built file (offline after first load).
import { readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';
const dist = new URL('../dist/', import.meta.url).pathname;
const files = [];
(function walk(d) { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else if (!f.endsWith('.map') && f !== 'sw.js') files.push(relative(dist, p)); } })(dist);
const h = createHash('sha256'); for (const f of files.sort()) h.update(f + readFileSync(join(dist, f)).length);
const version = h.digest('hex').slice(0, 12);
const list = ['./', ...files.map((f) => './' + f)];
writeFileSync(join(dist, 'sw.js'), `// generated by scripts/build-sw.mjs
const CACHE = 'doucovani-${version}';
const ASSETS = ${JSON.stringify(list)};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(caches.match(req, { ignoreSearch: req.mode === 'navigate' }).then((hit) => hit || fetch(req).then((res) => {
    if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
    return res;
  }).catch(() => req.mode === 'navigate' ? caches.match('./index.html') : Response.error())));
});
`);
console.log(`sw.js: ${list.length} files, cache ${version}`);
